// ---- Pixel primitives -------------------------------------------------------
void Overlay::put_pixel(uint8_t* buf, int w, int h, int x, int y, RGBA c) {
    if (x < 0 || y < 0 || x >= w || y >= h) return;
    uint8_t* p = buf + (y * w + x) * 4;
    p[0] = c.r; p[1] = c.g; p[2] = c.b; p[3] = c.a;
}

void Overlay::blend_pixel(uint8_t* buf, int w, int h, int x, int y, RGBA c) {
    if (x < 0 || y < 0 || x >= w || y >= h) return;
    uint8_t* p = buf + (y * w + x) * 4;
    if (c.a == 255) { p[0]=c.r; p[1]=c.g; p[2]=c.b; p[3]=255; return; }
    int a = c.a, ia = 255 - a;
    p[0] = (uint8_t)((c.r * a + p[0] * ia) / 255);
    p[1] = (uint8_t)((c.g * a + p[1] * ia) / 255);
    p[2] = (uint8_t)((c.b * a + p[2] * ia) / 255);
    p[3] = 255;
}

void Overlay::fill_rect(uint8_t* buf, int w, int h, int x, int y, int rw, int rh, RGBA c) {
    int x0 = std::max(0, x), y0 = std::max(0, y);
    int x1 = std::min(w, x + rw), y1 = std::min(h, y + rh);
    for (int yy = y0; yy < y1; ++yy)
        for (int xx = x0; xx < x1; ++xx)
            blend_pixel(buf, w, h, xx, yy, c);
}

void Overlay::stroke_rect(uint8_t* buf, int w, int h, int x, int y, int rw, int rh, RGBA c) {
    if (rw <= 0 || rh <= 0) return;
    for (int xx = x; xx < x + rw; ++xx) {
        blend_pixel(buf, w, h, xx, y,         c);
        blend_pixel(buf, w, h, xx, y + rh - 1, c);
    }
    for (int yy = y; yy < y + rh; ++yy) {
        blend_pixel(buf, w, h, x,         yy, c);
        blend_pixel(buf, w, h, x + rw - 1, yy, c);
    }
}

void Overlay::draw_panel(uint8_t* buf, int w, int h, int x, int y, int rw, int rh,
                         RGBA fill, RGBA edge) {
    fill_rect(buf, w, h, x, y, rw, rh, fill);
    stroke_rect(buf, w, h, x, y, rw, rh, edge);
}

// ---- Text -------------------------------------------------------------------
int Overlay::draw_char(uint8_t* buf, int w, int h, int x, int y, char ch,
                       RGBA color, int scale) {
    int idx = (unsigned char)ch - 0x20;
    if (idx < 0 || idx >= 96) idx = '?' - 0x20;
    const uint8_t* glyph = kFont8[idx];
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (1 << col)) {
                for (int sy = 0; sy < scale; ++sy)
                    for (int sx = 0; sx < scale; ++sx)
                        blend_pixel(buf, w, h, x + col * scale + sx, y + row * scale + sy, color);
            }
        }
    }
    return 8 * scale;
}

int Overlay::draw_text(uint8_t* buf, int w, int h, int x, int y,
                       const std::string& text, RGBA color, int scale) {
    int cx = x;
    for (char c : text) {
        if (c == '\n') { cx = x; y += 8 * scale + 1; continue; }
        draw_char(buf, w, h, cx, y, c, color, scale);
        cx += 8 * scale;
    }
    return cx - x;
}

int Overlay::text_width(const std::string& text, int scale) {
    return (int)text.size() * 8 * scale;
}

// ---- Toasts -----------------------------------------------------------------
void Overlay::post_toast(const std::string& text, float seconds, RGBA color) {
    toasts_.push_back({text, seconds, color});
    if (toasts_.size() > 6) toasts_.erase(toasts_.begin());
}

void Overlay::update(float dt) {
    for (auto& t : toasts_) t.remaining -= dt;
    toasts_.erase(std::remove_if(toasts_.begin(), toasts_.end(),
                                 [](const Toast& t){ return t.remaining <= 0.0f; }),
                  toasts_.end());
}

void Overlay::render_toasts(uint8_t* buf, int w, int h) {
    int y = h - 14;
    for (auto it = toasts_.rbegin(); it != toasts_.rend(); ++it) {
        int tw = text_width(it->text) + 8;
        int x  = w - tw - 6;
        RGBA bg = {0, 0, 0, 180};
        fill_rect(buf, w, h, x - 1, y - 2, tw + 2, 12, bg);
        stroke_rect(buf, w, h, x - 1, y - 2, tw + 2, 12, it->color);
        draw_text(buf, w, h, x + 4, y, it->text, it->color);
        y -= 14;
        if (y < 8) break;
    }
}

